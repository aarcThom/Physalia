    // FIELDS ==========================================================================================

    // The live inner document. Replaced with a fresh instance on each re-open so that
    // GH_Document.Read() always starts from a clean slate (avoids NRE from stale internal state
    // left by GH's close cycle on the previous instance).
    private GH_Document _internalDocument;

    // Snapshot of the inner document as XML. Captured in DocumentClosed before GH clears
    // the document's objects. Restored into a fresh document on next OpenEditor or SolveInstance.
    private string? _snapshotXml;

    // Maps outer input/output parameter InstanceGuid → inner hook InstanceGuid.
    // Rebuilt by SyncHooks() whenever parameters change or the inner document is restored.
    private Dictionary<Guid, Guid> _inputHookMap = new();
    private Dictionary<Guid, Guid> _outputHookMap = new();

    // Guards DocumentModified against re-entering ExpireSolution during our own solve cycle.
    private bool _solving;

    // Guards SyncOuterFromInner from running while SyncHooks() is pushing outer → inner,
    // preventing a re-entrant reverse sync.
    private bool _syncingHooks;

    // Parsed response from the last LLM call; null until a response has been received.
    private ClusterResponse? _lastResponse;

    // Component-not-found and wire-resolution errors from the last ApplyLlmResponse call.
    // Reported by GetFixMessage() so the auto-fix loop can correct them.
    private List<string> _lastClusterErrors = new ();

    // Maps component id → (GH name, formatted input NickNames, formatted output NickNames).
    // Populated during BuildInnerDocument and appended to the fix prompt so the LLM has
    // an exact NickName reference for every component it placed.
    private Dictionary<string, (string Name, string Inputs, string Outputs)> _componentReference = new ();

