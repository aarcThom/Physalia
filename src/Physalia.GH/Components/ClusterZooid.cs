    // SERIALIZATION ==========================================================================

    /// <summary>
    /// Serializes the cluster state so it survives save and reload.
    /// Uses <see cref="_snapshotXml"/> as the source of truth when the inner document
    /// has been cleared by GH (after Save and Close), falling back to the live document.
    /// </summary>
    /// <param name="writer">The GH_IWriter to write to.</param>
    /// <returns>true.</returns>
    public override bool Write(GH_IWriter writer)
    {
        string xml;
        if (_snapshotXml != null)
        {
            xml = _snapshotXml;
        }
        else
        {
            var archive = new GH_Archive();
            archive.AppendObject(_internalDocument, "ClusterDoc");
            xml = archive.Serialize_Xml();
        }

        writer.SetString("InternalDocumentXml", xml);

        if (_lastResponse != null)
            writer.SetString("ClusterResponseJson", JsonSerializer.Serialize(_lastResponse));

        return base.Write(writer);
    }

    /// <summary>
    /// Deserialises the cluster state. Stores the XML in <see cref="_snapshotXml"/>
    /// so the inner document can be restored into a fresh instance on first use.
    /// </summary>
    /// <param name="reader">The GH_IReader to read from.</param>
    /// <returns>true.</returns>
    public override bool Read(GH_IReader reader)
    {
        if (reader.ItemExists("InternalDocumentXml"))
            _snapshotXml = reader.GetString("InternalDocumentXml");

        string responseJson = string.Empty;
        if (reader.TryGetString("ClusterResponseJson", ref responseJson))
            _lastResponse = JsonSerializer.Deserialize<ClusterResponse>(responseJson);

        return base.Read(reader);
    }

